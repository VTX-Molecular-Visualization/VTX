TITLES = {
    FUNCTIONS_PAGE: "Functions",
    "Python-API-Systems": "Systems and topology",
    "Python-API-Selection": "Selection",
    "Python-API-Camera": "Camera",
    "Python-API-Trajectory": "Trajectory",
    "Python-API-Presets": "Presets and colors",
    "Python-API-Types": "Base types",
    OTHER_PAGE: "Other",
}


def overloads(p_function):
    """Split a pybind11 docstring into (signature, description) pairs."""
    if inspect.isfunction(p_function):
        signature = p_function.__name__ + str(inspect.signature(p_function))
        return [(signature, " ".join((p_function.__doc__ or "").split()))]
    lines = (p_function.__doc__ or "").strip().splitlines()
    if len(lines) > 1 and lines[1].strip() == "Overloaded function.":
        parts = re.split(r"^\d+\. ", "\n".join(lines[2:]).strip(), flags=re.MULTILINE)
        blocks = [part.strip().splitlines() for part in parts if part.strip()]
    else:
        blocks = [lines]
    return [(block[0].strip(), " ".join(line.strip() for line in block[1:]).strip()) for block in blocks if block]


CPP_TYPES = {
    "VTX::App::PythonBinding::Preset::Handle<VTX::Renderer::Representation>": "RepresentationPreset",
    "VTX::App::PythonBinding::Preset::Handle<VTX::Renderer::Color::Layout>": "ColorLayoutPreset",
    "VTX::App::PythonBinding::Preset::Handle<VTX::Renderer::GraphicsConfig>": "GraphicsConfigPreset",
    "VTX::Renderer::E_COLOR_SCHEME_SECONDARY_STRUCTURE": "SECONDARY_STRUCTURE_COLOR_SCHEME",
    "VTX::Renderer::E_COLOR_SCHEME": "COLOR_SCHEME",
    "VTX::App::System::E_VISIBLE_STATE": "VISIBLE_STATE",
    "VTX::App::System::E_SELECTION_STATE": "SELECTION_STATE",
}

TYPE_PATTERNS = [
    (r"typing\.SupportsInt \| typing\.SupportsIndex", "int"),
    (r"typing\.SupportsFloat \| typing\.SupportsIndex", "float"),
    (r"os\.PathLike \| str \| bytes", "str"),
    (r'typing\.Annotated\[(.+?), "FixedSize\(\d+\)"\]', r"\1"),
    (r"<([\w.]+): [^>]+>", r"\1"),
    (r"VTX::App::PythonBinding::Topology::(\w+)", r"\1"),
    (r"\bvtx\.", ""),
    (r"\b([\w.]+(?:\[[^\]]*\])?) \| None\b", r"Optional[\1]"),
]


def clean_types(p_text):
    """Replace C++ type names and verbose typing hints by their Python names."""
    text = p_text
    for cpp_name, python_name in CPP_TYPES.items():
        text = text.replace(cpp_name, python_name)
    for pattern, replacement in TYPE_PATTERNS:
        text = re.sub(pattern, replacement, text)
    if "::" in text:
        print(f"Warning: unresolved C++ type in {text}")
    return text


def clean_signature(p_signature):
    signature = re.sub(r"self: [\w.]+(, )?", "", p_signature)
    return re.sub(r" -> None$", "", clean_types(signature))


def property_type(p_property):
    if p_property.fget is None:
        return ""
    signatures = overloads(p_property.fget)
    match = re.search(r"-> (.+)$", signatures[0][0]) if signatures else None
    return clean_types(match.group(1)) if match else ""


def property_doc(p_property):
    doc = (p_property.__doc__ or "").strip()
    return "" if doc.startswith("(") else doc


def escape(p_text):
    return p_text.replace("|", "\\|")


def describe_class(p_class):
    rows = []
    init = p_class.__dict__.get("__init__")
    if init is not None and (init.__doc__ or "").startswith("__init__("):
        for signature, doc in overloads(init):
            rows.append((clean_signature(signature).replace("__init__", p_class.__name__, 1), "", doc or "Constructor."))

    for name, member in sorted(vars(p_class).items()):
        if name.startswith("_"):
            continue
        if isinstance(member, property):
            type_name = property_type(member)
            access = " *(read-only)*" if member.fset is None else ""
            rows.append((f"{name}: {type_name}" if type_name else name, access, property_doc(member)))
            continue
        attribute = getattr(p_class, name)
        if callable(attribute):
            prefix = "static " if isinstance(member, staticmethod) else ""
            for signature, doc in overloads(attribute):
                rows.append((prefix + clean_signature(signature), "", doc))

    text = f"## {p_class.__name__}\n\n{(p_class.__doc__ or '').strip()}\n\n"
    if rows:
        text += "| Member | Description |\n|---|---|\n"
        for code, suffix, doc in rows:
            text += f"| `{escape(code)}`{suffix} | {escape(doc)} |\n"
    return text + "\n"


def describe_enum(p_enum):
    values = ", ".join(f"`{name}`" for name in p_enum.__members__)
    return f"## {p_enum.__name__}\n\n{escape((p_enum.__doc__ or '').strip())}\n\nValues: {values}\n\n"


def page_of(p_name):
    return next((page for page, names in PAGES.items() if p_name in names), OTHER_PAGE)


def describe_functions(p_functions, p_objects):
    text = "| Function | Description |\n|---|---|\n"
    for name in sorted(p_functions):
        for signature, doc in overloads(p_functions[name]):
            text += f"| `{escape(clean_signature(signature))}` | {escape(doc)} |\n"
    if p_objects:
        text += "\n## Objects\n\n| Object | Type |\n|---|---|\n"
        for name in sorted(p_objects):
            type_name = type(p_objects[name]).__name__
            text += f"| `vtx.{name}` | [{type_name}]({page_of(type_name)}#{type_name.lower()}) |\n"
    return text + "\n"


def write_page(p_page, p_body):
    path = os.path.join(OUTPUT_DIR, p_page + ".md")
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write(HEADER + f"# Python API: {TITLES[p_page]}\n\n" + p_body)
    print(f"Written {path}")


def generate():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for file_name in os.listdir(OUTPUT_DIR):
        path = os.path.join(OUTPUT_DIR, file_name)
        if file_name.startswith("Python-API-") and file_name.endswith(".md"):
            with open(path, encoding="utf-8") as file:
                generated = file.read(len(HEADER)) == HEADER
            if generated:
                os.remove(path)

    classes, functions, objects = {}, {}, {}
    for name, member in vars(vtx).items():
        if name.startswith("_") or name in SKIPPED or inspect.ismodule(member):
            continue
        if inspect.isclass(member):
            classes[name] = member
        elif callable(member):
            functions[name] = member
        else:
            objects[name] = member

    classified = {name for names in PAGES.values() for name in names}
    unclassified = sorted(set(classes) - classified)
    for name in unclassified:
        print(f"Warning: {name} is not assigned to a page, written to {OTHER_PAGE}.")
    for name in sorted(classified - set(classes)):
        print(f"Warning: {name} is listed in PAGES but does not exist.")

    write_page(FUNCTIONS_PAGE, describe_functions(functions, objects))
    pages = dict(PAGES)
    if unclassified:
        pages[OTHER_PAGE] = unclassified
    for page, names in pages.items():
        body = ""
        for name in names:
            if name not in classes:
                continue
            member = classes[name]
            body += describe_enum(member) if issubclass(member, enum.Enum) else describe_class(member)
        write_page(page, body)


try:
    generate()
finally:
    vtx.quit()
